-- ============================================================================
-- Migración 012 · Tokens de reset de contraseña por email
-- ============================================================================

CREATE TABLE IF NOT EXISTS password_reset_tokens (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id      integer NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
    token_hash      varchar(128) NOT NULL,  -- hash del token (bcrypt), NO guardar token plano
    expira_en       timestamptz NOT NULL,   -- ahora + 30 minutos
    usado_en        timestamptz,            -- NULL = no usado; timestamp = ya usado
    creado_en       timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_password_reset_tokens_usuario
    ON password_reset_tokens (usuario_id);

CREATE INDEX IF NOT EXISTS idx_password_reset_tokens_expira
    ON password_reset_tokens (expira_en)
    WHERE usado_en IS NULL;

COMMENT ON TABLE password_reset_tokens IS 'Tokens para reset de contraseña vía email (hash bcrypt, 30 min expiración, un solo uso)';
COMMENT ON COLUMN password_reset_tokens.token_hash IS 'bcrypt(token_plano, 12)';
COMMENT ON COLUMN password_reset_tokens.expira_en IS 'Expiración del token (30 minutos desde creación)';
COMMENT ON COLUMN password_reset_tokens.usado_en IS 'Timestamp cuando se usó el token; NULL = no usado';